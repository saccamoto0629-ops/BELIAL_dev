def validate_order_result_update(old: OrderResult, new: OrderResult) -> None:
    """Raise unless ``new`` is a legal successor snapshot of ``old`` (PR #87).

    ``validate_order_state_transition`` checks only the state pair; this
    validator checks the CONTENT of the update. It applies to every update,
    including same-state re-observations of terminal states (a FILLED order
    re-observed as FILLED must not change content), and to resolutions of
    UNKNOWN (the resolved ``new`` must satisfy both its own construction
    invariants and these update invariants — so e.g. an UNKNOWN snapshot
    holding partial fills can resolve to PARTIALLY_FILLED / FILLED /
    CANCELLED but never back to ACCEPTED / REJECTED, and an UNKNOWN snapshot
    holding the full requested quantity can only resolve to FILLED).

    Invariants:

    - identity/request fields (``client_order_id`` / ``symbol`` / ``side`` /
      ``order_type`` / ``requested_quantity`` / ``requested_price``) are
      unchanged
    - ``filled_quantity`` is monotonically non-decreasing,
      ``remaining_quantity`` monotonically non-increasing
    - ``old.fills`` is preserved as a prefix of ``new.fills`` — no fill is
      removed, reordered or altered, and an appended fill never reuses an
      existing ``fill_id``
    - ``broker_order_id`` may go ``None -> value`` (broker ack arrived) and
      ``value -> None`` stays forbidden. ``value A -> value B`` is allowed
      EXACTLY for an audited Order Reissue (Issue #102): the new snapshot's
      ``superseded_broker_order_ids`` must extend the old chain by ``A``
      first (``old chain + (A,)`` is a prefix of the new chain — further
      appended ids are reissues learned in the same observation), so a
      current-id change can never silently drop the history. With the id
      unchanged the chain must be unchanged too, and no id ever re-enters
      the chain (uniqueness is a construction invariant)
    - ``updated_at_utc`` is monotonically non-decreasing for every update
    - a same-state re-observation of a TERMINAL state must be identical in
      every field except ``updated_at_utc`` — a settled fill price or a
      reject reason can never be rewritten afterwards

    Type-malformed inputs raise ``BrokerInvalidRequestError``; invariant
    violations raise ``ValueError`` (same boundary as ``OrderResult``).
    """
    if not isinstance(old, OrderResult) or not isinstance(new, OrderResult):
        raise BrokerInvalidRequestError(
            f"both snapshots must be OrderResult instances, got {old!r} -> {new!r}"
        )
    validate_order_state_transition(old.state, new.state)

    for field_name in _IMMUTABLE_RESULT_FIELDS:
        if getattr(old, field_name) != getattr(new, field_name):
            raise ValueError(
                f"{field_name} must not change between snapshots: "
                f"{getattr(old, field_name)!r} -> {getattr(new, field_name)!r}"
            )

    if new.filled_quantity < old.filled_quantity:
        raise ValueError(
            f"filled_quantity must not decrease: {old.filled_quantity} -> {new.filled_quantity}"
        )
    if new.remaining_quantity > old.remaining_quantity:
        raise ValueError(
            f"remaining_quantity must not increase: "
            f"{old.remaining_quantity} -> {new.remaining_quantity}"
        )

    if new.fills[: len(old.fills)] != old.fills:
        raise ValueError(
            "old fills must be preserved unchanged as a prefix of new fills "
            "(no removal, reordering, or alteration of an existing fill_id)"
        )
    # Each appended fill joins the seen-ID set, so a duplicate among the
    # appended fills themselves is caught here too (construction already
    # enforces per-snapshot uniqueness; this keeps the update validator
    # self-sufficient).
    seen_fill_ids = {f.fill_id for f in old.fills}
    for appended in new.fills[len(old.fills):]:
        if appended.fill_id in seen_fill_ids:
            raise ValueError(
                f"appended fill reuses existing fill_id {appended.fill_id!r}"
            )
        seen_fill_ids.add(appended.fill_id)

    if old.broker_order_id is not None and new.broker_order_id != old.broker_order_id:
        if new.broker_order_id is None:
            raise ValueError(
                f"broker_order_id may never be dropped: "
                f"{old.broker_order_id!r} -> None"
            )
        # Order Reissue (Issue #102): a current-id change is legal only as an
        # AUDITED chain append — the old chain followed by the old current id
        # must lead the new chain. Any additional appended ids are further
        # reissues learned within the same observation (multi-hop). A change
        # that loses or rewrites the history is refused.
        expected_prefix = old.superseded_broker_order_ids + (old.broker_order_id,)
        if new.superseded_broker_order_ids[: len(expected_prefix)] != expected_prefix:
            raise ValueError(
                f"broker_order_id change {old.broker_order_id!r} -> "
                f"{new.broker_order_id!r} without an audited reissue chain: "
                f"superseded_broker_order_ids must start with "
                f"{expected_prefix!r}, got {new.superseded_broker_order_ids!r}"
            )
    elif old.superseded_broker_order_ids != new.superseded_broker_order_ids:
        if old.broker_order_id is None:
            # The broker ack (None -> value) may reveal a chain that predates
            # our first id knowledge (e.g. an UNKNOWN order resolved by a
            # query that reconstructs the reissue history) — but a chain can
            # never appear without a current id, and never shrink.
            if new.broker_order_id is None or (
                new.superseded_broker_order_ids[: len(old.superseded_broker_order_ids)]
                != old.superseded_broker_order_ids
            ):
                raise ValueError(
                    "superseded_broker_order_ids may only grow: "
                    f"{old.superseded_broker_order_ids!r} -> "
                    f"{new.superseded_broker_order_ids!r}"
                )
        else:
            raise ValueError(
                "superseded_broker_order_ids must not change while the current "
                f"broker_order_id {old.broker_order_id!r} is unchanged: "
                f"{old.superseded_broker_order_ids!r} -> "
                f"{new.superseded_broker_order_ids!r}"
            )

    if new.updated_at_utc < old.updated_at_utc:
        raise ValueError(
            f"updated_at_utc must not go backwards: "
            f"{old.updated_at_utc.isoformat()} -> {new.updated_at_utc.isoformat()}"
        )

    if old.state is new.state and old.state in TERMINAL_ORDER_STATES:
        # A terminal outcome is settled: re-observation may only refresh the
        # timestamp, never the content (average_fill_price, reject_reason,
        # fills, IDs, ... are all frozen).
        for spec in fields(OrderResult):
            if spec.name == "updated_at_utc":
                continue
            if getattr(old, spec.name) != getattr(new, spec.name):
                raise ValueError(
                    f"terminal same-state re-observation must not change "
                    f"{spec.name}: {getattr(old, spec.name)!r} -> {getattr(new, spec.name)!r}"
                )


# --- connection identity -----------------------------------------------------


@dataclass(frozen=True)
class BrokerConnectionIdentity:
    """The immutable connection identity a broker implementation reports
    about ITSELF (Issue #75): which execution mode its connection belongs to
    and the exact endpoint/config target it talks to.

    The identity must be derived from the implementation's own
    construction-time configuration -- never from caller-side declarations --
    so a mode/target claim can never drift from what the instance actually
    connects to. It must stay CONSTANT for the lifetime of the instance.

    ``mode`` / ``target`` are deliberately plain strings: the broker layer
    owns no execution-layer vocabulary (dependency direction, Issue #73).
    The execution layer maps ``mode`` onto its own enum and cross-checks the
    implementation's concrete type; unknown modes fail there, closed.
    """

    mode: str
    target: str

    def __post_init__(self) -> None:
        _require_non_empty_str(self.mode, "mode")
        _require_non_empty_str(self.target, "target")
        if self.mode != self.mode.strip():
            raise BrokerInvalidRequestError(
                f"mode {self.mode!r} carries surrounding whitespace"
            )
        if self.target != self.target.strip():
            raise BrokerInvalidRequestError(
                f"target {self.target!r} carries surrounding whitespace"
            )


