r"""Broker-agnostic common models for the future Live Execution layer (Issue #73).

*** BOUNDARY ONLY. NOTHING IN THIS PACKAGE PLACES A REAL ORDER. ***

This module defines the vocabulary that future Live Execution code and future
broker adapters (e.g. an OANDA adapter) will share:

- order request / order result / fills / positions / account state
- the order-state machine (including the "outcome unknown after timeout" case)
- the typed broker-error taxonomy

It deliberately contains NO broker-specific fields, NO network code, NO
persistence, and it is NOT used by Paper Execution. Paper Execution
(``paper-execution/``) remains an independent virtual-execution layer that
never talks to a broker; its ``position_models`` vocabulary (long/short,
pending/open/closed/...) is a different domain and is intentionally NOT
merged into these order models.

Design decisions (Issue #73):

- ``Decimal`` for every price / quantity / money amount. This is a new,
  independent boundary, so it is not bound by Paper Execution's float
  convention; live-order arithmetic must not accumulate float error.
- All timestamps are timezone-aware UTC ``datetime`` values. Naive datetimes
  are rejected.
- IDs with different meanings live in different fields: ``client_order_id``
  is generated by the caller and is the caller-side key at this boundary;
  ``broker_order_id`` is assigned by the broker and only exists once the
  broker acknowledged the order. They are never mixed in one field.
- Error style is a combination: a definitive business answer from the broker
  (filled / partially filled / still working / rejected) is a RETURN VALUE
  (``OrderResult``); an infrastructure failure (timeout, communication
  failure, cancellation failure, invalid request, not found) is a typed
  ``BrokerError`` exception carrying a ``BrokerErrorCode``. A rejection is
  therefore distinguishable from a timeout by construction: rejection is
  ``OrderState.REJECTED`` (broker said no), timeout is ``BrokerTimeoutError``
  plus ``OrderState.UNKNOWN`` (the broker MAY have accepted the order — the
  model never lets a timeout collapse into "not placed" or "rejected").
- Caller-supplied data crossing the boundary is validated with
  ``BrokerInvalidRequestError``; internal model invariants (result
  consistency, state transitions) raise ``ValueError``, matching the
  repository's existing model-validation style.
"""

from __future__ import annotations

import enum
import hashlib
from dataclasses import dataclass, field, fields
from datetime import datetime
from decimal import Decimal

# --- error taxonomy ---------------------------------------------------------


class BrokerErrorCode(enum.Enum):
    """Machine-checkable failure categories for broker operations.

    A plain order rejection is NOT listed here: the broker answered
    definitively, so it is modelled as ``OrderState.REJECTED`` on the
    returned ``OrderResult`` (with ``reject_reason``), not as an exception.
    """

    TIMEOUT = "timeout"
    COMMUNICATION_FAILURE = "communication_failure"
    CANCELLATION_FAILURE = "cancellation_failure"
    INVALID_REQUEST = "invalid_request"
    NOT_FOUND = "not_found"
    # Issue #79: categories a REAL broker endpoint can answer with. They stay
    # broker-agnostic (HTTP status codes and vendor payloads are adapter
    # concerns and must be translated before crossing this boundary).
    AUTHENTICATION_FAILURE = "authentication_failure"
    RATE_LIMITED = "rate_limited"


class BrokerError(Exception):
    """Base class for broker-operation failures. Check ``code``, not strings."""

    code: BrokerErrorCode

    def __init__(self, message: str, *, client_order_id: str | None = None):
        super().__init__(message)
        self.client_order_id = client_order_id


class BrokerTimeoutError(BrokerError):
    """The operation timed out; the broker MAY have accepted the order.

    After this error the order's state is ``OrderState.UNKNOWN`` — never
    assume "not placed" or "rejected" until a later query resolves it.
    """

    code = BrokerErrorCode.TIMEOUT


class BrokerCommunicationError(BrokerError):
    """The request could not be exchanged with the broker (transport failure)."""

    code = BrokerErrorCode.COMMUNICATION_FAILURE


class BrokerCancellationError(BrokerError):
    """The broker refused or failed to cancel an order (e.g. already filled)."""

    code = BrokerErrorCode.CANCELLATION_FAILURE


class BrokerInvalidRequestError(BrokerError):
    """The request itself is malformed (bad quantity, duplicate ID, ...)."""

    code = BrokerErrorCode.INVALID_REQUEST


class BrokerOrderNotFoundError(BrokerError):
    """No order is known under the given ``client_order_id``."""

    code = BrokerErrorCode.NOT_FOUND


class BrokerAuthenticationError(BrokerError):
    """The broker refused the credentials (Issue #79).

    The message must never contain the credential values themselves --
    adapters raise this with a static description only.
    """

    code = BrokerErrorCode.AUTHENTICATION_FAILURE


class BrokerRateLimitError(BrokerError):
    """The broker throttled the request (rate limit, Issue #79).

    Retrying is the CALLER's decision; adapters never resend on their own.
    """

    code = BrokerErrorCode.RATE_LIMITED


# --- enums ------------------------------------------------------------------


class RejectionCategory(enum.Enum):
    """Broker-neutral normalized classification of a definitive order
    rejection (Issue #114).

    A CLOSED vocabulary: adapters map their native rejection codes onto
    these members INSIDE the adapter (the mapping tables live with each
    adapter, and the mapping input is the native response the adapter saw),
    so no broker-specific code is ever a DECISION input on this side of the
    boundary — the execution layer acts on this enum and never parses
    ``reject_reason`` text.

    ``reject_reason`` is the deliberate exception to "broker strings stay
    inside the adapter": it is the AUDIT field, and adapters put the
    broker's own reason there after redacting and truncating it, so an
    ordinary rejection does carry sanitized native text. That is a
    pre-existing contract which classification neither widens nor replaces —
    it adds no new retention path and never an un-redacted one.

    Anything an adapter cannot map — unknown codes, missing codes, and
    snapshots written before classification existed — is ``UNCLASSIFIED``,
    which is fail-closed: it never qualifies for automatic reissue
    (``docs/architecture/execution_reissue.md`` owns the category ->
    reissue-eligibility table).
    """

    TRANSIENT = "transient"
    PARAMETER = "parameter"
    ACCOUNT = "account"
    INSTRUMENT = "instrument"
    BROKER_INTERNAL = "broker_internal"
    UNCLASSIFIED = "unclassified"


class OrderSide(enum.Enum):
    BUY = "buy"
    SELL = "sell"


class OrderType(enum.Enum):
    MARKET = "market"
    LIMIT = "limit"


class PositionSide(enum.Enum):
    LONG = "long"
    SHORT = "short"


class OrderState(enum.Enum):
    """Broker-order lifecycle states (Issue #73).

    ``PENDING``   — submitted by us, no broker acknowledgement yet.
    ``ACCEPTED``  — broker acknowledged the order; nothing filled yet.
    ``PARTIALLY_FILLED`` — some quantity filled, some still working.
    ``FILLED``    — fully filled (terminal).
    ``CANCELLED`` — cancelled before completion (terminal).
    ``REJECTED``  — broker definitively refused the order (terminal).
    ``UNKNOWN``   — the outcome could not be confirmed (e.g. timeout). The
                    broker may or may not hold the order; NOT terminal — a
                    later query / reconciliation resolves it. Deliberately a
                    separate state from ``REJECTED``.

    UNKNOWN contract (Issue #73 / PR #87): "unknown" qualifies the BROKER
    CONFIRMATION, not the fill amount. An UNKNOWN snapshot may therefore
    carry any *known-so-far* fills — none, partial, or even full requested
    quantity (fills observed before confirmation was lost) — as long as
    ``0 <= filled_quantity <= requested_quantity`` and the fills sum matches,
    and ``broker_order_id`` may be present or absent. What UNKNOWN never
    asserts is a final outcome: it must not be collapsed into "not placed",
    "rejected" or "filled" until a later query resolves it.
    """

    PENDING = "pending"
    ACCEPTED = "accepted"
    PARTIALLY_FILLED = "partially_filled"
    FILLED = "filled"
    CANCELLED = "cancelled"
    REJECTED = "rejected"
    UNKNOWN = "unknown"


TERMINAL_ORDER_STATES: frozenset[OrderState] = frozenset(
    {OrderState.FILLED, OrderState.CANCELLED, OrderState.REJECTED}
)

# The authoritative order-state CHANGE map: which *different* states an order
# may move to. UNKNOWN can be resolved to any concrete state by a later query;
# terminal states are never left again. Same-state updates (re-observing the
# same snapshot, e.g. broker polling, or another partial fill while
# PARTIALLY_FILLED) are NOT state changes and are always allowed by
# ``validate_order_state_transition`` — including for terminal states
# (FILLED -> FILLED is a re-observation, FILLED -> CANCELLED stays forbidden).
ORDER_STATE_TRANSITIONS: dict[OrderState, frozenset[OrderState]] = {
    OrderState.PENDING: frozenset(
        {
            OrderState.ACCEPTED,
            OrderState.PARTIALLY_FILLED,
            OrderState.FILLED,
            OrderState.CANCELLED,
            OrderState.REJECTED,
            OrderState.UNKNOWN,
        }
    ),
    OrderState.ACCEPTED: frozenset(
        {
            OrderState.PARTIALLY_FILLED,
            OrderState.FILLED,
            OrderState.CANCELLED,
            OrderState.REJECTED,
            OrderState.UNKNOWN,
        }
    ),
    OrderState.PARTIALLY_FILLED: frozenset(
        {
            OrderState.FILLED,
            OrderState.CANCELLED,
            OrderState.UNKNOWN,
        }
    ),
    OrderState.UNKNOWN: frozenset(
        {
            OrderState.ACCEPTED,
            OrderState.PARTIALLY_FILLED,
            OrderState.FILLED,
            OrderState.CANCELLED,
            OrderState.REJECTED,
        }
    ),
    OrderState.FILLED: frozenset(),
    OrderState.CANCELLED: frozenset(),
    OrderState.REJECTED: frozenset(),
}


def validate_order_state_transition(old: OrderState, new: OrderState) -> None:
    """Raise ValueError unless ``old -> new`` is an allowed update (Issue #73).

    Same-state updates (``old is new``) are always allowed, for EVERY state
    including terminal ones: broker polling re-observes the same snapshot,
    and a PARTIALLY_FILLED order may take further partial fills. Only a
    *change* of state is checked against ``ORDER_STATE_TRANSITIONS`` — so
    e.g. FILLED -> FILLED passes while FILLED -> CANCELLED raises.
    """
    if not isinstance(old, OrderState) or not isinstance(new, OrderState):
        raise BrokerInvalidRequestError(
            f"states must be OrderState members, got {old!r} -> {new!r}"
        )
    if old is new:
        return
    allowed = ORDER_STATE_TRANSITIONS[old]
    if new not in allowed:
        raise ValueError(
            f"invalid order state transition {old.value!r} -> {new.value!r}; "
            f"allowed: {sorted(s.value for s in allowed)}"
        )


# --- validation helpers -----------------------------------------------------


def _require_utc(value: datetime, field_name: str) -> None:
    if not isinstance(value, datetime) or value.tzinfo is None or value.utcoffset() is None:
        raise BrokerInvalidRequestError(f"{field_name} must be a timezone-aware datetime")
    if value.utcoffset().total_seconds() != 0:
        raise BrokerInvalidRequestError(f"{field_name} must be UTC (utcoffset 0), got {value.tzinfo}")


def _require_decimal(value, field_name: str, *, allow_negative: bool = False) -> None:
    if not isinstance(value, Decimal) or not value.is_finite():
        raise BrokerInvalidRequestError(f"{field_name} must be a finite Decimal, got {value!r}")
    if not allow_negative and value < 0:
        raise BrokerInvalidRequestError(f"{field_name} must be >= 0, got {value!r}")


def _require_positive_decimal(value, field_name: str) -> None:
    _require_decimal(value, field_name)
    if value <= 0:
        raise BrokerInvalidRequestError(f"{field_name} must be > 0, got {value!r}")


def _require_non_empty_str(value, field_name: str) -> None:
    if not isinstance(value, str) or not value.strip():
        raise BrokerInvalidRequestError(f"{field_name} must be a non-empty string, got {value!r}")


def weighted_average_price(fills: tuple["Fill", ...]) -> Decimal | None:
    """Quantity-weighted average price over ``fills`` (None when empty)."""
    if not fills:
        return None
    total_qty = sum((f.quantity for f in fills), Decimal(0))
    total_notional = sum((f.price * f.quantity for f in fills), Decimal(0))
    return total_notional / total_qty


# --- request / result models ------------------------------------------------


@dataclass(frozen=True)
class OrderRequest:
    """A broker-agnostic order request.

    ``client_order_id`` is generated by the CALLER and is the key used at this
    boundary (submit / cancel / query). The broker-assigned ID appears only on
    results as ``broker_order_id``. ``limit_price`` is required for LIMIT
    orders and forbidden for MARKET orders.
    """

    client_order_id: str
    symbol: str
    side: OrderSide
    order_type: OrderType
    quantity: Decimal
    created_at_utc: datetime
    limit_price: Decimal | None = None

    def __post_init__(self) -> None:
        _require_non_empty_str(self.client_order_id, "client_order_id")
        _require_non_empty_str(self.symbol, "symbol")
        if not isinstance(self.side, OrderSide):
            raise BrokerInvalidRequestError(f"side must be an OrderSide, got {self.side!r}")
        if not isinstance(self.order_type, OrderType):
            raise BrokerInvalidRequestError(f"order_type must be an OrderType, got {self.order_type!r}")
        _require_positive_decimal(self.quantity, "quantity")
        _require_utc(self.created_at_utc, "created_at_utc")
        if self.order_type is OrderType.LIMIT:
            if self.limit_price is None:
                raise BrokerInvalidRequestError("limit_price is required for LIMIT orders")
            _require_positive_decimal(self.limit_price, "limit_price")
        elif self.limit_price is not None:
            raise BrokerInvalidRequestError("limit_price must be None for MARKET orders")


@dataclass(frozen=True)
class Fill:
    """One execution (partial or full) of an order."""

    fill_id: str
    price: Decimal
    quantity: Decimal
    filled_at_utc: datetime

    def __post_init__(self) -> None:
        _require_non_empty_str(self.fill_id, "fill_id")
        _require_positive_decimal(self.price, "price")
        _require_positive_decimal(self.quantity, "quantity")
        _require_utc(self.filled_at_utc, "filled_at_utc")


@dataclass(frozen=True)
class OrderResult:
    """A snapshot of one order's state as reported by a broker.

    Quantities are tracked explicitly: ``requested_quantity`` (ordered),
    ``filled_quantity`` (executed so far) and ``remaining_quantity``
    (validated to equal requested - filled). ``requested_price`` (the LIMIT
    price, None for MARKET) and ``average_fill_price`` / ``fills`` are held
    SEPARATELY so tests can compare the requested price against the actual
    execution price (price deviation / slippage).

    Validation boundary (PR #87): malformed FIELDS — wrong types coming from
    a caller/adapter, e.g. a raw string instead of an enum member, a list
    instead of a fills tuple, an empty ``reject_reason`` — raise
    ``BrokerInvalidRequestError``. CROSS-FIELD consistency violations —
    quantity arithmetic, state x fill constraints, ``reject_reason`` present
    for the wrong state — raise ``ValueError`` (internal model invariants).

    Invariants: fills must sum to ``filled_quantity``; each state constrains
    ``filled_quantity`` (see ``__post_init__``); ``reject_reason`` exists
    exactly for REJECTED and is then a non-empty string, and
    ``rejection_category`` follows the same cross-constraint (Issue #114:
    required for REJECTED, None for every other state). ``reject_reason``
    stays the ONLY free-text audit field and keeps its safety contract —
    adapters redact then truncate before it enters this model, so it may
    carry the broker's sanitized reason text — while ``rejection_category``
    is the machine-checkable classification the execution layer may act on
    and, being a closed enum, never carries broker-native codes.
    ``average_fill_price`` is not required to equal the recomputed weighted
    average exactly (a real broker may round), but must be present iff any
    fill exists.

    UNKNOWN contract: an UNKNOWN snapshot may carry any known-so-far fills —
    none, partial, or full requested quantity — with or without a
    ``broker_order_id`` (see ``OrderState``). UNKNOWN constrains nothing
    beyond the generic quantity invariants, because it asserts only that the
    broker-side outcome is unconfirmed.

    Order Reissue contract (Issue #102): some brokers reissue the remaining
    quantity of a partially filled order as a NEW broker order under a NEW
    broker order id. ``broker_order_id`` therefore always names the CURRENT
    actionable broker order (the one ``get_order`` / ``cancel_order``
    operate on), and ``superseded_broker_order_ids`` is the append-only,
    oldest-first history of the broker order ids this order previously lived
    under. The chain never rewrites: ids are unique, never contain the
    current id, and a non-empty chain requires both a current
    ``broker_order_id`` and ``filled_quantity > 0`` (a reissue exists only
    because a partial fill happened). ``original_broker_order_id`` exposes
    the parent identity for audit. The ``client_order_id`` /
    ``execution_request_id`` correlation is untouched by a reissue: the
    caller-side key never changes.
    """

    client_order_id: str
    broker_order_id: str | None
    state: OrderState
    symbol: str
    side: OrderSide
    order_type: OrderType
    requested_quantity: Decimal
    filled_quantity: Decimal
    remaining_quantity: Decimal
    requested_price: Decimal | None
    average_fill_price: Decimal | None
    updated_at_utc: datetime
    fills: tuple[Fill, ...] = field(default_factory=tuple)
    reject_reason: str | None = None
    superseded_broker_order_ids: tuple[str, ...] = ()
    rejection_category: RejectionCategory | None = None

    def __post_init__(self) -> None:
        # --- field/type validation (caller-supplied data) -> BrokerInvalidRequestError
        _require_non_empty_str(self.client_order_id, "client_order_id")
        if self.broker_order_id is not None:
            _require_non_empty_str(self.broker_order_id, "broker_order_id")
        if not isinstance(self.state, OrderState):
            raise BrokerInvalidRequestError(f"state must be an OrderState, got {self.state!r}")
        if not isinstance(self.side, OrderSide):
            raise BrokerInvalidRequestError(f"side must be an OrderSide, got {self.side!r}")
        if not isinstance(self.order_type, OrderType):
            raise BrokerInvalidRequestError(
                f"order_type must be an OrderType, got {self.order_type!r}"
            )
        if not isinstance(self.fills, tuple):
            raise BrokerInvalidRequestError(f"fills must be a tuple, got {type(self.fills).__name__}")
        for entry in self.fills:
            if not isinstance(entry, Fill):
                raise BrokerInvalidRequestError(f"every fills entry must be a Fill, got {entry!r}")
        if self.reject_reason is not None:
            _require_non_empty_str(self.reject_reason, "reject_reason")
        if self.rejection_category is not None and not isinstance(
            self.rejection_category, RejectionCategory
        ):
            raise BrokerInvalidRequestError(
                f"rejection_category must be a RejectionCategory or None, "
                f"got {self.rejection_category!r}"
            )
        if not isinstance(self.superseded_broker_order_ids, tuple):
            raise BrokerInvalidRequestError(
                "superseded_broker_order_ids must be a tuple, got "
                f"{type(self.superseded_broker_order_ids).__name__}"
            )
        for entry in self.superseded_broker_order_ids:
            _require_non_empty_str(entry, "superseded_broker_order_ids entry")
        if len(set(self.superseded_broker_order_ids)) != len(self.superseded_broker_order_ids):
            raise BrokerInvalidRequestError(
                "superseded_broker_order_ids must be unique, got "
                f"{self.superseded_broker_order_ids!r}"
            )
        _require_non_empty_str(self.symbol, "symbol")
        _require_positive_decimal(self.requested_quantity, "requested_quantity")
        _require_decimal(self.filled_quantity, "filled_quantity")
        # remaining may only be validated against the equality invariant below
        # (a negative value there is an inconsistency -> ValueError, not a
        # malformed field), so the field-level check allows negatives.
        _require_decimal(self.remaining_quantity, "remaining_quantity", allow_negative=True)
        if self.requested_price is not None:
            _require_positive_decimal(self.requested_price, "requested_price")
        _require_utc(self.updated_at_utc, "updated_at_utc")

        if self.filled_quantity > self.requested_quantity:
            raise ValueError(
                f"filled_quantity {self.filled_quantity} exceeds requested {self.requested_quantity}"
            )
        if self.remaining_quantity != self.requested_quantity - self.filled_quantity:
            raise ValueError(
                "remaining_quantity must equal requested_quantity - filled_quantity "
                f"({self.requested_quantity} - {self.filled_quantity}), got {self.remaining_quantity}"
            )
        fills_total = sum((f.quantity for f in self.fills), Decimal(0))
        if fills_total != self.filled_quantity:
            raise ValueError(
                f"fills sum {fills_total} does not match filled_quantity {self.filled_quantity}"
            )
        # A duplicated fill_id would double-count the same execution while
        # still passing the quantity-sum check, so IDs must be unique per
        # snapshot (PR #87).
        fill_ids = [f.fill_id for f in self.fills]
        if len(fill_ids) != len(set(fill_ids)):
            duplicates = sorted({fid for fid in fill_ids if fill_ids.count(fid) > 1})
            raise ValueError(f"fill_id values must be unique within a snapshot: {duplicates}")
        if (self.average_fill_price is None) != (not self.fills):
            raise ValueError("average_fill_price must be present iff fills is non-empty")
        if self.average_fill_price is not None:
            _require_positive_decimal(self.average_fill_price, "average_fill_price")

        # --- cross-field consistency (ValueError) ---
        # Adapter translation mistakes must be caught at construction: the
        # requested price exists exactly for LIMIT orders, and PENDING means
        # "no broker acknowledgement yet", so no broker_order_id can exist.
        if self.order_type is OrderType.LIMIT and self.requested_price is None:
            raise ValueError("LIMIT order results require a requested_price")
        if self.order_type is OrderType.MARKET and self.requested_price is not None:
            raise ValueError("MARKET order results must have requested_price=None")
        if self.state is OrderState.PENDING and self.broker_order_id is not None:
            raise ValueError("pending means no broker acknowledgement yet: broker_order_id must be None")

        state, filled = self.state, self.filled_quantity
        if state in (OrderState.PENDING, OrderState.ACCEPTED, OrderState.REJECTED) and filled != 0:
            raise ValueError(f"state {state.value!r} requires filled_quantity == 0, got {filled}")
        if state is OrderState.PARTIALLY_FILLED and not (0 < filled < self.requested_quantity):
            raise ValueError(
                f"partially_filled requires 0 < filled < requested, got {filled}/{self.requested_quantity}"
            )
        if state is OrderState.FILLED and filled != self.requested_quantity:
            raise ValueError(
                f"filled requires filled_quantity == requested_quantity, got {filled}/{self.requested_quantity}"
            )
        if state is OrderState.CANCELLED and filled >= self.requested_quantity:
            raise ValueError("cancelled requires filled_quantity < requested_quantity")
        if (state is OrderState.REJECTED) != (self.reject_reason is not None):
            raise ValueError("reject_reason must be set exactly when state is rejected")
        if (state is OrderState.REJECTED) != (self.rejection_category is not None):
            raise ValueError(
                "rejection_category must be set exactly when state is rejected"
            )
        if state in (OrderState.ACCEPTED, OrderState.PARTIALLY_FILLED, OrderState.FILLED):
            if self.broker_order_id is None:
                raise ValueError(f"state {state.value!r} requires a broker_order_id")

        # Reissue chain invariants (Issue #102): the chain lists PAST ids, so
        # it can never contain the current id; a chain exists only for an
        # order the broker acknowledged (current id known) AND partially
        # filled (a reissue is caused by a partial fill, so a chain without
        # fills would fabricate a reissue that cannot have happened).
        if self.broker_order_id is not None and self.broker_order_id in self.superseded_broker_order_ids:
            raise ValueError(
                f"superseded_broker_order_ids must not contain the current "
                f"broker_order_id {self.broker_order_id!r}"
            )
        if self.superseded_broker_order_ids:
            if self.broker_order_id is None:
                raise ValueError(
                    "a reissue chain requires a current broker_order_id; "
                    "superseded ids cannot exist without one"
                )
            if self.filled_quantity <= 0:
                raise ValueError(
                    "a reissue chain requires filled_quantity > 0: the remaining "
                    "quantity is only ever reissued after a partial fill"
                )

    @property
    def original_broker_order_id(self) -> str | None:
        """The FIRST broker order id this order lived under (Issue #102).

        Equals ``broker_order_id`` while no reissue happened; after one or
        more reissues it is the head of the superseded chain (the parent /
        original broker order identity, kept for audit)."""
        if self.superseded_broker_order_ids:
            return self.superseded_broker_order_ids[0]
        return self.broker_order_id

    @property
    def all_broker_order_ids(self) -> tuple[str, ...]:
        """Every broker order id this order has lived under, oldest first,
        current id last (Issue #102 audit view). Empty while no broker
        acknowledgement exists."""
        if self.broker_order_id is None:
            return self.superseded_broker_order_ids
        return self.superseded_broker_order_ids + (self.broker_order_id,)

    @property
    def price_deviation(self) -> Decimal | None:
        """``average_fill_price - requested_price`` (None unless both known).

        Positive means the order filled above the requested price.
        """
        if self.average_fill_price is None or self.requested_price is None:
            return None
        return self.average_fill_price - self.requested_price


